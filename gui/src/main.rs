/// True when turns should be forwarded to a remote daemon instead of running
/// in this process.
fn is_cloud(location: &str) -> bool {
    location.eq_ignore_ascii_case("cloud")
}

/// Trim and sanity-check a daemon base URL, so a typo produces a clear message
/// rather than an opaque transport error.
fn normalize_base_url(raw: &str) -> Result<String, String> {
    let url = raw.trim().trim_end_matches('/');
    if url.is_empty() {
        return Err("尚未填写云服务地址，请在「设置 → 执行位置」中填写".to_string());
    }
    let lower = url.to_ascii_lowercase();
    if !lower.starts_with("http://") && !lower.starts_with("https://") {
        return Err("云服务地址需要以 http:// 或 https:// 开头".to_string());
    }
    Ok(url.to_string())
}

/// Turn a transport/status failure into something the user can act on.
fn cloud_err(e: ureq::Error) -> String {
    match e {
        ureq::Error::Status(code, _) => match code {
            401 => "云服务拒绝访问：Token 不正确".to_string(),
            404 => "云服务地址不正确：找不到该接口（请确认端口）".to_string(),
            405 => "云服务地址不正确：该路径不接受 POST".to_string(),
            _ => format!("云服务返回错误状态 {code}"),
        },
        ureq::Error::Transport(t) => format!("无法连接云服务：{t}"),
    }
}

/// Turn the model-service probe's failure into something actionable. The wording
/// is about the model API, so it says "API Key / Base URL" rather than the cloud
/// daemon's "Token / 服务地址".
fn model_err(e: ureq::Error) -> String {
    match e {
        ureq::Error::Status(code, _) => match code {
            401 | 403 => "API Key 不正确或没有访问权限".to_string(),
            404 => {
                "Base URL 不正确：找不到 /models（有些服务需要带上 /v1 之类的版本路径）".to_string()
            }
            _ => format!("模型服务返回错误状态 {code}"),
        },
        ureq::Error::Transport(t) => format!("无法连接模型服务：{t}"),
    }
}

/// Trim and sanity-check the model service base URL. Kept separate from
/// `normalize_base_url` only because the empty message must point at the model
/// settings rather than the cloud ones.
fn model_base_url(raw: &str) -> Result<String, String> {
    let url = raw.trim().trim_end_matches('/');
    if url.is_empty() {
        return Err("尚未填写 Base URL".to_string());
    }
    let lower = url.to_ascii_lowercase();
    if !lower.starts_with("http://") && !lower.starts_with("https://") {
        return Err("Base URL 需要以 http:// 或 https:// 开头".to_string());
    }
    Ok(url.to_string())
}

/// Probe the local model service with the values the user just typed: a
/// `GET {base_url}/models` costs no tokens and works on any OpenAI-compatible
/// endpoint, so a wrong Key can be told apart from a wrong Base URL before
/// running a whole task. Nothing is saved here.
/// 这是一次最多等 8 秒的网络请求：留在主线程上会把整个窗口冻 8 秒。
#[tauri::command]
async fn model_health(base_url: String, api_key: String) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<String, String> {
        let url = model_base_url(&base_url)?;
        if api_key.trim().is_empty() {
            return Err("尚未填写 API Key".to_string());
        }
        let agent = ureq::AgentBuilder::new()
            .timeout(std::time::Duration::from_secs(8))
            .build();
        let resp = agent
            .get(&format!("{url}/models"))
            .set("Authorization", &format!("Bearer {}", api_key.trim()))
            .call()
            .map_err(model_err)?;
        let body: serde_json::Value = resp
            .into_json()
            .map_err(|e| format!("模型服务响应无法解析：{e}"))?;
        let count = body
            .get("data")
            .and_then(|d| d.as_array())
            .map(|a| a.len())
            .unwrap_or(0);
        Ok(if count > 0 {
            format!("连接正常 · 可用模型 {count} 个")
        } else {
            "连接正常".to_string()
        })
    })
    .await
    .map_err(|e| format!("检测线程异常：{e}"))?
}

/// Probe a daemon's `GET /health` with the values the user just typed, without
/// saving them first (`/health` needs no auth, but we send the token anyway).
#[tauri::command]
async fn cloud_health(url: String, token: String) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<String, String> {
        let base = normalize_base_url(&url)?;
        let agent = ureq::AgentBuilder::new()
            .timeout(std::time::Duration::from_secs(8))
            .build();
        let mut req = agent.get(&format!("{base}/health"));
        let token = token.trim();
        if !token.is_empty() {
            req = req.set("Authorization", &format!("Bearer {token}"));
        }
        let resp = req.call().map_err(cloud_err)?;
        let body: serde_json::Value = resp
            .into_json()
            .map_err(|e| format!("云服务响应无法解析：{e}"))?;
        let sessions = body.get("sessions").and_then(|s| s.as_u64()).unwrap_or(0);
        Ok(format!("连接正常 · 当前 {sessions} 个会话"))
    })
    .await
    .map_err(|e| format!("检测线程异常：{e}"))?
}

/// Forward one turn to the remote daemon. A streaming daemon answers with NDJSON
/// events that are forwarded to the webview as they arrive, so a cloud task looks
/// like a local one; an older daemon still answers with a single JSON body, which
/// is handled below. Either reply carries the token usage this request added on
/// the daemon side, so cloud tasks show the same counter as local ones.
fn cloud_run(
    s: &AppSettings,
    session: Option<&str>,
    prompt: &str,
    images: &[String],
    ui: &Arc<Ui>,
) -> Result<String, String> {
    let base = normalize_base_url(&s.cloud_url)?;
    // A remote turn can take minutes (the daemon runs the whole tool loop), so
    // cap *idle* time rather than the whole call: a healthy stream keeps
    // resetting the read timeout, while a wedged daemon fails within minutes
    // instead of leaving the task in "执行中" until a 15-minute cap fires.
    let agent = ureq::AgentBuilder::new()
        .timeout_connect(std::time::Duration::from_secs(15))
        .timeout_read(std::time::Duration::from_secs(300))
        .build();
    let mut req = agent
        .post(&base)
        .set("Content-Type", "application/json")
        // Per-task conversation isolation on the daemon side.
        .set("X-Session-Id", session.unwrap_or("default"));
    let token = s.cloud_token.trim();
    if !token.is_empty() {
        req = req.set("Authorization", &format!("Bearer {token}"));
    }
    // Attached images ride along as data URLs; omitting the field when there are
    // none keeps the request identical to what older daemons expect.
    let payload = if images.is_empty() {
        json!({ "prompt": prompt, "stream": true })
    } else {
        json!({ "prompt": prompt, "stream": true, "images": images })
    };
    let resp = req.send_json(payload).map_err(cloud_err)?;
    // A daemon that supports streaming answers with NDJSON and keeps the socket
    // open while it works; anything else returns one JSON body as before, which
    // is parsed (with its usage) further down.
    let kind = resp.header("content-type").unwrap_or("").to_string();
    if kind.starts_with(NDJSON_CONTENT_TYPE) {
        let text = cloud_read_stream(resp, ui)?;
        ui.flush();
        return Ok(text);
    }
    let body: serde_json::Value = resp
        .into_json()
        .map_err(|e| format!("云服务响应无法解析：{e}"))?;
    if let Some(err) = body.get("error").and_then(|v| v.as_str()) {
        return Err(format!("云端执行失败：{err}"));
    }
    // Reported by the daemon as an increment for this request; an older daemon
    // omits it, in which case nothing is sent and the counter stays hidden.
    if let Some(u) = body.get("usage") {
        let field = |k: &str| u.get(k).and_then(|v| v.as_u64()).unwrap_or(0);
        ui.usage(
            field("requests"),
            field("prompt_tokens"),
            field("completion_tokens"),
        );
    }
    Ok(body
        .get("response")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_string())
}

/// Content type a streaming daemon replies with (newline-delimited JSON events).
const NDJSON_CONTENT_TYPE: &str = "application/x-ndjson";

/// What came out of one NDJSON event stream.
#[derive(Default)]
struct StreamOutcome {
    /// Text of the final `done` event (empty until one arrives).
    text: String,
    /// A `done` event was seen, i.e. the turn finished on purpose.
    done: bool,
    /// The daemon reported a failure; the message is shown to the user instead of
    /// an empty answer.
    error: Option<String>,
    /// The user pressed Stop; the partial stream is a normal ending, not a fault.
    cancelled: bool,
}

/// Parse one daemon event stream, handing every event to `on` as it is read.
/// Kept separate from the Tauri plumbing so the framing and the failure rules can
/// be tested without an app handle.
fn read_ndjson<R: BufRead>(
    reader: R,
    mut on: impl FnMut(&serde_json::Value),
    mut stopped: impl FnMut() -> bool,
) -> Result<StreamOutcome, String> {
    let mut out = StreamOutcome::default();
    for line in reader.lines() {
        // The stop flag is checked at event boundaries — the same rule as a local
        // turn — so a cloud turn stops as soon as the daemon sends its next event.
        if stopped() {
            out.cancelled = true;
            break;
        }
        let line = line.map_err(|e| format!("读取云端流失败：{e}"))?;
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let ev: serde_json::Value = match serde_json::from_str(line) {
            Ok(v) => v,
            // A partial or malformed line must not abort a turn that is otherwise
            // fine; skip it and keep reading.
            Err(_) => continue,
        };
        match ev.get("type").and_then(|t| t.as_str()).unwrap_or("") {
            "done" => {
                out.text = ev
                    .get("response")
                    .and_then(|v| v.as_str())
                    .unwrap_or("")
                    .to_string();
                out.done = true;
            }
            "error" => {
                out.error = Some(
                    ev.get("error")
                        .and_then(|v| v.as_str())
                        .unwrap_or("未知错误")
                        .to_string(),
                );
            }
            _ => {}
        }
        on(&ev);
    }
    Ok(out)
}

/// Consume the daemon's event stream, forwarding every event to the webview as it
/// arrives so a cloud task looks and behaves like a local one. Returns the final
/// reply text. An `error` event, or a stream that ends before its `done` line, is
/// reported as a failure rather than passed off as an empty answer.
fn cloud_read_stream(resp: ureq::Response, ui: &Arc<Ui>) -> Result<String, String> {
    let outcome = read_ndjson(
        BufReader::new(resp.into_reader()),
        |ev| {
            let text = |k: &str| ev.get(k).and_then(|v| v.as_str()).unwrap_or("").to_string();
            match ev.get("type").and_then(|t| t.as_str()).unwrap_or("") {
                "delta" => ui.push(&text("text")),
                "tool" => ui.tool(text("name"), text("summary"), text("output")),
                "note" => ui.note(text("text")),
                "usage" => {
                    let n = |k: &str| ev.get(k).and_then(|v| v.as_u64()).unwrap_or(0);
                    ui.usage(n("requests"), n("prompt_tokens"), n("completion_tokens"));
                }
                _ => {}
            }
        },
        agent::interrupt::take,
    )?;
    ui.flush();
    // A user-requested stop ends the turn on purpose: keep whatever was streamed
    // and let the UI report "task stopped" instead of a stream error.
    if outcome.cancelled {
        return Ok(outcome.text);
    }
    if let Some(err) = outcome.error {
        return Err(format!("云端执行失败：{err}"));
    }
    if !outcome.done {
        return Err("云端流提前结束，无法确认这一轮已完成".to_string());
    }
    Ok(outcome.text)
}

/// Run one task to completion.
///
/// 这必须是 `async` 命令并把整轮工作丢进阻塞线程池：Tauri v2 里**同步命令会在主
/// 线程上执行**，而一轮对话要跑几十秒到几分钟。主线程被占住期间窗口收不到系统
/// 消息，既不会重绘也处理不了点击，表现就是「AI 一开口整个界面就卡死、鼠标都
/// 不动，直到回答结束」——流式增量的 `emit` 也排在这条被堵死的主线程上，根本
/// 送不到前端，于是看起来像「一次性憋到最后」。
#[tauri::command]
async fn run_task(
    app: AppHandle,
    prompt: String,
    // Execution location of the task being run; falls back to the default from
    // settings when the caller does not send one.
    location: Option<String>,
    // Attached images as `data:image/...;base64,...` URLs (Vision-capable models
    // only). Both paths forward the same list: locally into the multimodal user
    // message, remotely in the request body.
    images: Option<Vec<String>>,
) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || {
        let state = app.state::<AppState>();
        run_task_inner(&state, prompt, location, images)
    })
    .await
    .map_err(|e| format!("运行线程异常：{e}"))?
}

/// 一轮对话的实际执行体：阻塞式调用模型 / 转发云端流，因此只允许跑在阻塞线程池。
fn run_task_inner(
    state: &AppState,
    prompt: String,
    location: Option<String>,
    images: Option<Vec<String>>,
) -> Result<String, String> {
    let images = images.unwrap_or_default();
    // A stop flag left over from an earlier turn must not cancel this prompt at
    // iteration zero (the cloud reader checks it before the first event).
    agent::interrupt::take();
    // Drop any unflushed tail from a previous turn before writing this one.
    state.ui.discard();
    let session = acquire(&state.session).clone();
    {
        // Cloud turns never touch the local agent: the daemon owns the model key,
        // the workspace and the permission mode.
        let settings = acquire(&state.settings).clone();
        let cloud = match location.as_deref() {
            Some(loc) => is_cloud(loc),
            None => is_cloud(&settings.location),
        };
        if cloud {
            // Flush even when the stream fails: the tail is part of this turn's
            // answer, and leaving it in the shared buffer leaks it into the next
            // answer.
            let result = cloud_run(&settings, session.as_deref(), &prompt, &images, &state.ui);
            state.ui.flush();
            return result;
        }
    }
    {
        // A settings change that arrived while an earlier turn was running was
        // written to disk without rebuilding the agent; apply it now, while no
        // turn holds the lock, so this turn already uses the new settings.
        if std::mem::take(&mut *acquire(&state.rebind)) {
            let session = acquire(&state.session).clone();
            let ws = keep_workspace(state);
            let model = keep_model(state);
            let persona = keep_persona(state);
            bind_agent(
                state,
                session.as_deref(),
                ws.as_deref(),
                model.as_deref(),
                persona.as_deref(),
            );
        }
        let mut guard = acquire(&state.agent);
        if guard.is_none() {
            let settings = acquire(&state.settings).clone();
            let ws = active_workspace(state);
            let model = keep_model(state);
            let persona = keep_persona(state);
            *guard = Some(build_agent(
                &settings,
                &state.ui,
                session.as_deref(),
                &ws,
                model.as_deref(),
                persona.as_deref(),
            )?);
        }
    }

    let mut guard = acquire(&state.agent);
    let agent = guard.as_mut().ok_or("agent not initialised")?;
    let result = agent.run(user_content(&prompt, &images));
    drop(guard);

    state.ui.flush();
    result
}

