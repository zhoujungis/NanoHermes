    #[test]
    fn export_task_writes_into_the_exports_dir_and_avoids_overwriting() {
        let dir = data_dir().join("exports");
        std::fs::create_dir_all(&dir).unwrap();
        let tag = format!("export-test-{}", std::process::id());
        // 清掉上一次遗留的同名前缀文件，保证 -2 后缀断言稳定。
        if let Ok(rd) = std::fs::read_dir(&dir) {
            for e in rd.flatten() {
                if e.file_name().to_string_lossy().starts_with(&tag) {
                    let _ = std::fs::remove_file(e.path());
                }
            }
        }

        let p1 = export_task_inner(format!("../{tag}"), "# hi\n".to_string()).unwrap();
        let p1b = PathBuf::from(&p1);
        assert_eq!(
            p1b.parent().unwrap(),
            dir,
            "导出必须落在 exports 目录内，不能跳出"
        );
        assert_eq!(std::fs::read_to_string(&p1b).unwrap(), "# hi\n");
        let name1 = p1b.file_name().unwrap().to_string_lossy().to_string();
        assert!(name1.ends_with(".md"));
        assert!(
            !name1.contains('/') && !name1.contains('\\'),
            "文件名不能带路径分隔符"
        );

        let p2 = export_task_inner(format!("../{tag}"), "second".to_string()).unwrap();
        let p2b = PathBuf::from(&p2);
        assert_ne!(p1, p2, "同名导出不能覆盖已有文件");
        assert!(
            p2b.file_name()
                .unwrap()
                .to_string_lossy()
                .ends_with("-2.md"),
            "第二次导出应带 -2 后缀"
        );

        let _ = std::fs::remove_file(&p1b);
        let _ = std::fs::remove_file(&p2b);
    }
