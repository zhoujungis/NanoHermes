/// Event channel names shared with the frontend (`ui/index.html`).
const EVENT_DELTA: &str = "nanohermes://delta";
const EVENT_TOOL: &str = "nanohermes://tool";
const EVENT_NOTE: &str = "nanohermes://note";
const EVENT_USAGE: &str = "nanohermes://usage";

/// Flush buffered streamed text once it reaches this many characters (or on a
/// newline) so the webview is not flooded with one IPC message per token.
const DELTA_FLUSH_CHARS: usize = 48;

/// Tool results can carry whole file contents or long command output. Cap what
/// crosses IPC so a single call cannot balloon the message; the GUI shows the
/// excerpt with a "truncated" marker.
const MAX_TOOL_OUTPUT: usize = 8000;

/// Truncate `s` on a UTF-8 boundary, telling the reader how much was dropped.
fn clip(s: &str, max: usize) -> String {
    if s.len() <= max {
        return s.to_string();
    }
    let mut end = max;
    while end > 0 && !s.is_char_boundary(end) {
        end -= 1;
    }
    format!("{}\n…（已截断，完整输出 {} 字节）", &s[..end], s.len())
}

