/// Directories the file picker never descends into.
const SKIP_DIRS: &[&str] = &[
    ".git",
    "node_modules",
    "target",
    "dist",
    "build",
    "out",
    ".next",
    ".venv",
    "venv",
    "__pycache__",
    ".idea",
    ".vscode",
];

/// Upper bounds so a huge workspace cannot stall the webview with a giant list.
const MAX_FILES: usize = 3000;
const MAX_DEPTH: usize = 6;

fn walk_files(root: &std::path::Path, rel: &str, depth: usize, out: &mut Vec<String>) {
    if out.len() >= MAX_FILES || depth > MAX_DEPTH {
        return;
    }
    let dir = if rel.is_empty() {
        root.to_path_buf()
    } else {
        root.join(rel)
    };
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return;
    };
    let mut items: Vec<_> = entries.filter_map(|e| e.ok()).collect();
    items.sort_by_key(|e| e.file_name());
    for entry in items {
        if out.len() >= MAX_FILES {
            return;
        }
        let name = entry.file_name().to_string_lossy().to_string();
        if name.starts_with('.') {
            continue;
        }
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        let child = if rel.is_empty() {
            name.clone()
        } else {
            format!("{rel}/{name}")
        };
        if kind.is_dir() {
            if SKIP_DIRS.contains(&name.as_str()) {
                continue;
            }
            walk_files(root, &child, depth + 1, out);
        } else if kind.is_file() {
            out.push(child);
        }
    }
}

/// List the files of the current workspace for the composer's `+` picker.
/// 遍历整个工作区是同步 IO，仓库大时要走几秒，必须放阻塞线程池。
#[tauri::command]
async fn list_workspace_files(app: AppHandle) -> Result<Vec<String>, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<Vec<String>, String> {
        let state = app.state::<AppState>();
        let ws = active_workspace(&state);
        let root = PathBuf::from(&ws);
        if !root.is_dir() {
            return Err(format!("工作区目录不存在：{ws}"));
        }
        let mut out = Vec::new();
        walk_files(&root, "", 0, &mut out);
        Ok(out)
    })
    .await
    .map_err(|e| format!("读取线程异常：{e}"))?
}

/// Read a single text file for the results panel preview. The path must resolve
/// inside the workspace so a crafted value cannot read arbitrary files.
#[tauri::command]
async fn read_file_preview(app: AppHandle, path: String) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<String, String> {
        const MAX_BYTES: u64 = 200 * 1024;
        let state = app.state::<AppState>();
        let ws = active_workspace(&state);
        let root = std::fs::canonicalize(&ws).map_err(|e| format!("工作区不可用：{e}"))?;
        let requested = PathBuf::from(&path);
        let candidate = if requested.is_absolute() {
            requested
        } else {
            root.join(requested)
        };
        let full = std::fs::canonicalize(&candidate).map_err(|e| format!("无法打开文件：{e}"))?;
        if !full.starts_with(&root) {
            return Err("该文件不在当前工作区内".to_string());
        }
        let meta = std::fs::metadata(&full).map_err(|e| e.to_string())?;
        if !meta.is_file() {
            return Err("这不是一个文件".to_string());
        }
        if meta.len() > MAX_BYTES {
            return Err(format!(
                "文件过大（{} KB），暂不支持预览",
                meta.len() / 1024
            ));
        }
        let bytes = std::fs::read(&full).map_err(|e| e.to_string())?;
        Ok(String::from_utf8_lossy(&bytes).to_string())
    })
    .await
    .map_err(|e| format!("读取线程异常：{e}"))?
}

/// Unified diff of one file against the workspace's Git HEAD, for the results
/// panel. Git is the only real source of "what changed", so when the workspace
/// is not a work tree the caller gets `repo: false` and the UI says so instead
/// of inventing a diff.
#[derive(Serialize)]
struct FileDiff {
    repo: bool,
    text: String,
}

/// 要起 git 子进程，输出还可能很大，绝不能同步跑在主线程上。
#[tauri::command]
async fn file_diff(app: AppHandle, path: String) -> Result<FileDiff, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<FileDiff, String> {
        const MAX_DIFF_BYTES: usize = 200 * 1024;
        let state = app.state::<AppState>();
        let ws = active_workspace(&state);
        let root = std::fs::canonicalize(&ws).map_err(|e| format!("工作区不可用：{e}"))?;
        if !root.is_dir() {
            return Err("工作区不可用，请先在设置里选择工作区".to_string());
        }
        // The touched path comes from a tool argument summary, so it may be
        // absolute, relative or even truncated. Resolve and confine it the same
        // way as the preview, then hand git a path *inside* the repository.
        let requested = PathBuf::from(&path);
        let candidate = if requested.is_absolute() {
            requested
        } else {
            root.join(requested)
        };
        let full = std::fs::canonicalize(&candidate).map_err(|e| format!("无法打开文件：{e}"))?;
        if !full.starts_with(&root) {
            return Err("该文件不在当前工作区内".to_string());
        }
        let rel = full.strip_prefix(&root).unwrap_or(&full);

        let probe = std::process::Command::new("git")
            .arg("-C")
            .arg(&root)
            .args(["rev-parse", "--is-inside-work-tree"])
            .output();
        match probe {
            Ok(out) if out.status.success() => {
                if String::from_utf8_lossy(&out.stdout).trim() != "true" {
                    return Ok(FileDiff {
                        repo: false,
                        text: String::new(),
                    });
                }
            }
            Ok(_) => {
                return Ok(FileDiff {
                    repo: false,
                    text: String::new(),
                })
            }
            Err(e) => return Err(format!("无法执行 git：{e}")),
        }

        // `HEAD` compares the working tree and the index against the last commit,
        // so both staged and unstaged edits of the agent show up.
        // The workspace is repo-controlled: `diff.external`, textconv drivers and
        // core.fsmonitor can all execute commands. Neutralise them so clicking a
        // file cannot run code outside the agent's permission mode and transcript.
        let out = std::process::Command::new("git")
            .arg("-C")
            .arg(&root)
            .args([
                "-c",
                "diff.external=",
                "-c",
                "core.fsmonitor=false",
                "--no-pager",
                "diff",
                "--no-ext-diff",
                "--no-textconv",
                "--no-color",
                "HEAD",
                "--",
            ])
            .arg(rel)
            .output()
            .map_err(|e| format!("无法执行 git：{e}"))?;
        if !out.status.success() {
            let err = String::from_utf8_lossy(&out.stderr);
            return Err(err.trim().to_string());
        }

        let mut text = String::from_utf8_lossy(&out.stdout).to_string();
        if text.len() > MAX_DIFF_BYTES {
            let cut = (0..=MAX_DIFF_BYTES)
                .rev()
                .find(|&i| text.is_char_boundary(i))
                .unwrap_or(0);
            text.truncate(cut);
            text.push_str("\n… 差异过长，已截断");
        }
        Ok(FileDiff { repo: true, text })
    })
    .await
    .map_err(|e| format!("差异线程异常：{e}"))?
}

/// Ask the turn that is running to stop. `run_task` runs on a worker thread, so
/// this command can be delivered while it is still going; the flag is checked at
/// the next step boundary, which means the model call or tool already in flight
/// finishes first.
#[tauri::command]
fn stop_task() {
    agent::interrupt::request();
}

/// Turn a task title into a plain file name: path separators and characters
/// Windows rejects become `-`, and the result never escapes the target folder.
fn safe_stem(raw: &str) -> String {
    const BAD: &[char] = &['/', '\\', ':', '*', '?', '"', '<', '>', '|'];
    let cleaned: String = raw
        .chars()
        .map(|c| {
            if c.is_control() || BAD.contains(&c) {
                '-'
            } else {
                c
            }
        })
        .collect();
    // Windows strips trailing dots, and a name of only dots is not usable.
    let trimmed = cleaned.trim().trim_matches('.');
    if trimmed.is_empty() {
        return "conversation".to_string();
    }
    let stem: String = trimmed.chars().take(60).collect();
    // Windows treats CON/NUL/COM1… as devices even when they carry an extension,
    // so `CON.md` would write to the console instead of a file.
    let upper = stem.split('.').next().unwrap_or("").to_ascii_uppercase();
    let device = matches!(upper.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        || (upper.len() == 4
            && (upper.starts_with("COM") || upper.starts_with("LPT"))
            && upper.as_bytes()[3].is_ascii_digit());
    if device {
        format!("_{stem}")
    } else {
        stem
    }
}

/// 导出的 Markdown 可能是整段长对话，写盘交给阻塞线程池。
#[tauri::command]
async fn export_task(name: String, text: String) -> Result<String, String> {
    tauri::async_runtime::spawn_blocking(move || export_task_inner(name, text))
        .await
        .map_err(|e| format!("导出线程异常：{e}"))?
}

/// `export_task` 的纯同步部分：挑一个不覆盖已有文件的安全文件名并写盘。
fn export_task_inner(name: String, text: String) -> Result<String, String> {
    let dir = data_dir().join("exports");
    std::fs::create_dir_all(&dir).map_err(|e| format!("无法创建导出目录：{e}"))?;
    let stem = safe_stem(&name);
    // `create_new` closes the check-then-write race: two overlapping exports of
    // the same title must get distinct files instead of one truncating the other.
    use std::io::Write as _;
    let mut n = 0u32;
    loop {
        let path = if n == 0 {
            dir.join(format!("{stem}.md"))
        } else {
            dir.join(format!("{stem}-{}.md", n + 1))
        };
        match std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
        {
            Ok(mut file) => {
                file.write_all(text.as_bytes())
                    .map_err(|e| format!("写入失败：{e}"))?;
                return Ok(path.to_string_lossy().to_string());
            }
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                n += 1;
                if n > 10_000 {
                    return Err("导出文件名冲突过多".to_string());
                }
            }
            Err(e) => return Err(format!("写入失败：{e}")),
        }
    }
}

