/// One sub-directory offered by the task-folder picker.
#[derive(Serialize)]
struct DirEntry {
    name: String,
    path: String,
}

/// Result of browsing one directory: where we are, how to go back up, and what
/// folders are inside.
#[derive(Serialize)]
struct DirListing {
    path: String,
    parent: Option<String>,
    dirs: Vec<DirEntry>,
}

fn home_dir() -> PathBuf {
    std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."))
}

/// List sub-directories for the picker that chooses a task's working folder.
/// `path` empty means "start from the current task workspace (or $HOME)".
/// Paths are returned as given rather than canonicalized, so Windows callers do
/// not get the `\\?\` verbatim prefix.
#[tauri::command]
async fn list_dirs(app: AppHandle, path: Option<String>) -> Result<DirListing, String> {
    tauri::async_runtime::spawn_blocking(move || -> Result<DirListing, String> {
        let state = app.state::<AppState>();
        let base = match path.map(|p| p.trim().to_string()).filter(|p| !p.is_empty()) {
            Some(p) => PathBuf::from(p),
            None => {
                let ws = active_workspace(&state);
                if ws.trim().is_empty() {
                    home_dir()
                } else {
                    PathBuf::from(ws)
                }
            }
        };
        browse_dir(base)
    })
    .await
    .map_err(|e| format!("目录线程异常：{e}"))?
}

/// The pure half of `list_dirs`: sub-directories of one folder, plus the way
/// back up. Hidden entries are skipped so the picker stays readable.
fn browse_dir(base: PathBuf) -> Result<DirListing, String> {
    if !base.is_dir() {
        return Err(format!("不是有效的文件夹：{}", base.display()));
    }
    let entries = std::fs::read_dir(&base).map_err(|e| format!("无法读取目录：{e}"))?;
    let mut items: Vec<_> = entries.filter_map(|e| e.ok()).collect();
    items.sort_by_key(|e| e.file_name().to_string_lossy().to_lowercase());
    let dirs = items
        .into_iter()
        .filter(|e| e.file_type().map(|k| k.is_dir()).unwrap_or(false))
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            if name.starts_with('.') {
                return None;
            }
            Some(DirEntry {
                name,
                path: e.path().to_string_lossy().to_string(),
            })
        })
        .collect();
    Ok(DirListing {
        path: base.to_string_lossy().to_string(),
        parent: base.parent().map(|p| p.to_string_lossy().to_string()),
        dirs,
    })
}

